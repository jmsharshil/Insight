from datetime import date

from django.test import TestCase

from batches.models import Batch, Course, CourseLevel
from branch.models import Branch


class AutoGeneratedBatchNameTest(TestCase):
    def test_auto_generated_name_uses_three_uppercase_branch_letters(self):
        course = Course.objects.create(name='CSEET', code='CSEET-TEST')
        CourseLevel.objects.create(
            course=course,
            name='CSEET',
            course_type='cseet',
            order=1,
        )
        branch = Branch.objects.create(
            name='Ahmedabad Main',
            address='Test address',
            city='Ahmedabad',
            state='Gujarat',
            pincode='380001',
            phone='9876543210',
            email='branch@example.com',
        )
        batch = Batch(
            course=course,
            branch=branch,
            batch_attempt='june',
            attempt_year=2026,
            start_date=date(2026, 1, 1),
            end_date=date(2026, 6, 30),
            max_students=30,
        )

        batch.save()

        self.assertTrue(batch.name.startswith('AHM_'))
